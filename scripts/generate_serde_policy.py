def sql_string(value):
    return "'" + value.replace("'", "''") + "'"


def sql_text(value):
    """A SQL expression for a line that may hold control characters"""
    parts = re.split(r'([\x00-\x1f])', value)
    exprs = []
    for part in parts:
        if not part:
            continue
        if len(part) == 1 and ord(part) < 32:
            exprs.append(f'chr({ord(part)})')
        else:
            exprs.append(sql_string(part))
    return ' || '.join(exprs) if exprs else "''"


def slug(text):
    return re.sub(r'[^a-z0-9]+', '_', text.lower()).strip('_')


def select_list(columns):
    return ', '.join(c.split()[0] for c in columns.split(','))


class TestWriter:
    def __init__(self, serde):
        self.serde = serde
        self.table = serde['test_table']
        self.out = []
        self.count = 0
        self.keys = set()

    def emit(self, *lines):
        self.out.extend(lines)
        self.out.append('')

    def case(self, title, case):
        self.count += 1
        name = f"sp_{slug(self.serde['id'])}_{self.count}"
        columns = self.table['columns']
        cols = select_list(columns)
        ncols = len(cols.split(','))
        props = case.get('props', {})
        self.keys.update(props)
        self.out.append('#' + '-' * 75)
        self.out.append(f'# {title}')
        self.out.append('#' + '-' * 75)
        if 'fixture' in self.table:
            table = f"my_datalake.default.{self.table['fixture']}"
            location = f"{{DEFAULT_S3_LOCATION}}/{{TEST_DIR}}/serde_policy/{name}"
            self.emit('statement ok', f"CALL glue_set_table_location('{table}', '{location}');")
            if props:
                options = ', '.join(f'{sql_string(k)} = {sql_string(v)}' for k, v in props.items())
                self.emit('statement ok', f'ALTER TABLE {table} SET ({options});')
        else:
            table = f'my_datalake.default.{name}'
            location = f"{{DEFAULT_S3_LOCATION}}/{{TEST_DIR}}/default/{name}"
            options = ''.join(f', {sql_string(k)} = {sql_string(v)}' for k, v in props.items())
            self.emit('statement ok', f'DROP TABLE IF EXISTS {table};')
            self.emit('statement ok', f"CREATE TABLE {table} ({columns}) WITH ({self.table['create']}{options});")
        if case['direction'] == 'read':
            values = ', '.join(f'({sql_text(line)})' for line in case['lines'])
            self.emit(
                'statement ok',
                f"COPY (SELECT * FROM (VALUES {values}) t(line)) TO '{location}/data.txt' "
                "(FORMAT csv, HEADER false, QUOTE '', ESCAPE '');",
            )
            if case.get('warns'):
                self.emit('statement ok', "CALL enable_logging(level := 'warning', storage := 'memory');")
            query = f'SELECT {cols} FROM {table} ORDER BY ALL NULLS FIRST;'
            if 'error' in case:
                self.emit('statement error', query, '----', f"<REGEX>:.*{case['error']}.*")
            else:
                self.emit('query ' + 'T' * ncols, query, '----', *case['expect'])
            if case.get('warns'):
                keys = sorted(props)
                self.emit(
                    'query I',
                    f"SELECT count(*) > 0 FROM duckdb_logs WHERE message LIKE '%{table.split('.')[-1]}%SerDe property%"
                    "is not applied when reading';",
                    '----',
                    'true',
                )
                self.emit('statement ok', 'CALL disable_logging();')
                self.emit('statement ok', 'CALL truncate_duckdb_logs();')
        else:
            statement = f"INSERT INTO {table} VALUES {case['insert']};"
            if 'error' in case:
                self.emit('statement error', statement, '----', f"<REGEX>:.*{case['error']}.*")
            else:
                self.emit('statement ok', statement)
                if 'content' in case:
                    self.emit(
                        'query I',
                        "SELECT replace(replace(content, chr(1), '<01>'), chr(10), '<nl>') FROM "
                        f"read_text('{location}/*');",
                        '----',
                        case['content'],
                    )
                if 'expect' in case:
                    self.emit('query ' + 'T' * ncols, f'SELECT {cols} FROM {table} ORDER BY ALL NULLS FIRST;', '----',
                              *case['expect'])
        if 'fixture' in self.table and props:
            keys = ', '.join(sql_string(k) for k in props)
            self.emit('statement ok', f'ALTER TABLE {table} RESET ({keys});')
        elif 'fixture' not in self.table:
            self.emit('statement ok', f'DROP TABLE {table};')

    def text(self):
        s = self.serde
        header = [
            f"# name: test/sql/hive/dml/formats/serde_policy/{slug(s['id'])}.test",
            f"# description: generated from src/core/serde_policy.json: every {s['name']} property, read and written",
            '# group: [serde_policy]',
            '',
            '# This file is generated by scripts/generate_serde_policy.py, do not edit',
            '',
            'require httpfs',
            '',
            'require json',
            '',
            'require glue',
            '',
            'require-env GLUE_CATALOG_ID',
            '',
            'statement ok',
            "attach '{GLUE_CATALOG_ID}' as my_datalake (",
            '    TYPE glue,',
            "    ENDPOINT '{GLUE_ENDPOINT}',",
            "    DEFAULT_LOCATION '{DEFAULT_S3_LOCATION}/{TEST_DIR}'",
            ');',
            '',
        ]
        if 'fixture' in self.table:
            header += [
                f"# {self.table['fixture']} (scripts/docker-compose.yml) has no SerDe parameters: each case moves it to "
                'a location of its own and sets the properties as table parameters, which override SerDe parameters',
                '',
            ]
            if self.keys:
                keys = ', '.join(sql_string(k) for k in sorted(self.keys))
                header += ['# a run that failed half way may have left properties set', 'statement ok',
                           f"ALTER TABLE my_datalake.default.{self.table['fixture']} RESET ({keys});", '']
        return '\n'.join(header + self.out)


def generate_tests(policy):
    serdes = {s['id']: s for s in policy['serdes']}
    writers = {}
    coverage = []

    def writer(serde_id):
        if serde_id not in writers:
            if 'test_table' not in serdes[serde_id]:
                fail(f'SerDe {serde_id} has tests but no test_table')
            writers[serde_id] = TestWriter(serdes[serde_id])
        return writers[serde_id]

    for case in policy['serde_tests']:
        writer(case['serde']).case(f"{serdes[case['serde']]['name']} without properties ({case['direction']})", case)
    for prop in policy['properties']:
        for serde in prop['serdes']:
            cases = [c for c in prop['tests'] if c.get('serde', serde) == serde]
            for direction in ('read', 'write'):
                applies = direction == 'read' or serdes[serde]['writable']
                tested = any(c['direction'] == direction or direction in c.get('covers', []) for c in cases)
                if applies and not tested:
                    fail(f"property {prop['key']} of {serde} has no {direction} test")
                coverage.append((serde, prop['key'], direction, applies, tested))
            for case in cases:
                action = prop[case['direction']]['action']
                title = f"{prop['key']} ({serdes[serde]['name']}, {case['direction']}: {action}) " + json.dumps(
                    case.get('props', {}), ensure_ascii=False)
                writer(serde).case(title, case)
    os.makedirs(TEST_DIR, exist_ok=True)
    files = {}
    for serde_id, w in writers.items():
        files[os.path.join(TEST_DIR, slug(serde_id) + '.test')] = w.text()
    # SerDes the table refuses
    lines = [
        '# name: test/sql/hive/dml/formats/serde_policy/unsupported.test',
        '# description: generated from src/core/serde_policy.json: SerDes that are refused with their reason',
        '# group: [serde_policy]',
        '',
        '# This file is generated by scripts/generate_serde_policy.py, do not edit',
        '',
        'require httpfs',
        '',
        'require glue',
        '',
        'require-env GLUE_CATALOG_ID',
        '',
        'statement ok',
        "attach '{GLUE_CATALOG_ID}' as my_datalake (TYPE glue, ENDPOINT '{GLUE_ENDPOINT}');",
        '',
    ]
    for u in policy['unsupported_serdes']:
        if 'test' in u:
            lines += [
                'statement error',
                f"SELECT * FROM my_datalake.default.{u['test']['table']};",
                '----',
                f"<REGEX>:.*{u['test']['error']}.*",
                '',
            ]
    files[os.path.join(TEST_DIR, 'unsupported.test')] = '\n'.join(lines)
    return files, coverage


def main():
    policy = load()
    files, coverage = generate_tests(policy)
    files[HEADER] = generate_header(policy)
    files[DOCS] = generate_docs(policy)
    for path, text in files.items():
        with open(path, 'w') as f:
            f.write(text)
    applicable = [c for c in coverage if c[3]]
    print(f'{len(policy["properties"])} property rows, {len(set((c[0], c[1]) for c in coverage))} (SerDe, property) '
          f'pairs, {len(applicable)} (SerDe, property, direction) cells to test, '
          f'{sum(1 for c in applicable if c[4])} tested')
    print('wrote', ', '.join(os.path.relpath(p, ROOT) for p in sorted(files)))


if __name__ == '__main__':
    main()
