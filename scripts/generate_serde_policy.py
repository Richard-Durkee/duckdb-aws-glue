#!/usr/bin/env python3
"""Generate the SerDe policy table, its documentation and its tests from src/core/serde_policy.json.

Outputs:
  src/include/core/serde_policy_table.hpp     the C++ table ResolveSerDeProperties looks up
  docs/serde_properties.md                    the documentation table
  test/sql/hive/dml/formats/serde_policy/     one sqllogictest per SerDe, every declared property exercised

Fails when a property has no test for a direction it is declared for (reads always; writes when the SerDe is
writable and the property is not ignored on write without a test).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POLICY = os.path.join(ROOT, 'src', 'core', 'serde_policy.json')
HEADER = os.path.join(ROOT, 'src', 'include', 'core', 'serde_policy_table.hpp')
DOCS = os.path.join(ROOT, 'docs', 'serde_properties.md')
TEST_DIR = os.path.join(ROOT, 'test', 'sql', 'hive', 'dml', 'formats', 'serde_policy')

ACTIONS = {'apply': 'APPLY', 'ignore': 'IGNORE', 'warn': 'WARN', 'refuse': 'REFUSE'}
TRANSFORMS = {'text': 'TEXT', 'byte_code': 'BYTE_CODE', 'character': 'CHARACTER', 'count': 'COUNT', 'boolean': 'BOOLEAN'}
CONDITIONS = {
    None: 'ALWAYS',
    'set': 'SET',
    'non_empty': 'NON_EMPTY',
    'true': 'IS_TRUE',
    'positive': 'POSITIVE',
    'above_one': 'ABOVE_ONE',
    'not_utf8': 'NOT_UTF8',
}
CONDITION_TEXT = {
    None: '',
    'set': 'when set',
    'non_empty': 'when not empty',
    'true': "when 'true'",
    'positive': 'when above 0',
    'above_one': 'when above 1',
    'not_utf8': 'when not UTF-8',
}
CHECKS = {
    'no_nested_columns': 'SERDE_CHECK_NO_NESTED_COLUMNS',
    'delimiter_not_in_null_string': 'SERDE_CHECK_DELIMITER_NOT_IN_NULL_STRING',
    'single_byte_quote_escape': 'SERDE_CHECK_SINGLE_BYTE_QUOTE_ESCAPE',
    'single_byte_delimiter': 'SERDE_CHECK_SINGLE_BYTE_DELIMITER',
}
CHECK_TEXT = {
    'no_nested_columns': 'nested columns (array, map, struct) are refused',
    'delimiter_not_in_null_string': 'a NULL string holding the delimiter is refused',
    'single_byte_quote_escape': 'a quote or escape character of more than one byte is refused',
    'single_byte_delimiter': 'writes need a single-byte delimiter',
}
FORMATS = {'PARQUET', 'CSV', 'JSON', 'AVRO'}


def fail(message):
    sys.exit(f'generate_serde_policy.py: {message}')


def c_string(value):
    if value is None:
        return 'nullptr'
    out = '"'
    for byte in value.encode('utf-8'):
        char = chr(byte)
        if char == '"':
            out += '\\"'
        elif char == '\\':
            out += '\\\\'
        elif 32 <= byte < 127:
            out += char
        else:
            out += '\\%03o' % byte
    return out + '"'


def option_enum(name):
    return 'SerDeOption::' + name.upper() if name else 'SerDeOption::NONE'


def rule_serdes(prop):
    return prop['serdes']


def load():
    with open(POLICY) as f:
        policy = json.load(f)
    serde_ids = [s['id'] for s in policy['serdes']]
    for serde in policy['serdes']:
        if serde['format'] not in FORMATS:
            fail(f"SerDe {serde['id']}: unknown format {serde['format']}")
    for prop in policy['properties']:
        for serde in prop['serdes']:
            if serde not in serde_ids:
                fail(f"property {prop['key']}: unknown SerDe {serde}")
        for direction in ('read', 'write'):
            spec = prop[direction]
            if spec['action'] not in ACTIONS:
                fail(f"property {prop['key']}: unknown action {spec['action']}")
            if spec['action'] == 'apply' and spec.get('option') not in policy['options']:
                fail(f"property {prop['key']}: apply needs a known option")
            if spec['action'] in ('warn', 'refuse') and 'refuse_when' not in spec:
                fail(f"property {prop['key']}: {spec['action']} needs refuse_when")
    return policy


