def generate_header(policy):
    lines = [
        '// This file is generated by scripts/generate_serde_policy.py from src/core/serde_policy.json, do not edit',
        '#pragma once',
        '',
        '#include "core/serde_policy.hpp"',
        '',
        '// clang-format off',
        'namespace duckdb {',
        '',
        'static const SerDeDefinition SERDE_DEFINITIONS[] = {',
    ]
    for s in policy['serdes']:
        checks = ' | '.join(CHECKS[c] for c in s.get('checks', [])) or 'SERDE_CHECK_NONE'
        write_checks = ' | '.join(CHECKS[c] for c in s.get('write_checks', [])) or 'SERDE_CHECK_NONE'
        lines.append(
            f"    {{HiveSerDe::{s['id']}, {c_string(s['name'])}, {c_string(s['match'])}, HiveFileFormat::{s['format']}, "
            f"{c_string(s['library'])}, {c_string(s.get('input_format'))}, {c_string(s.get('output_format'))}, "
            f"{str(s.get('creates_format', False)).lower()}, {str(s['writable']).lower()}, "
            f"{c_string(s.get('write_refusal'))}, {str(s.get('quoted', False)).lower()}, "
            f"static_cast<uint8_t>({checks}), static_cast<uint8_t>({write_checks})}},"
        )
    lines += ['};', '', 'static const UnsupportedSerDe UNSUPPORTED_SERDES[] = {']
    for u in policy['unsupported_serdes']:
        lines.append(f"    {{{c_string(u['name'])}, {c_string(u['match'])}, {c_string(u['reason'])}}},")
    lines += ['};', '', 'static const SerDeOptionDefault SERDE_OPTION_DEFAULTS[] = {']
    for s in policy['serdes']:
        for direction in ('READ', 'WRITE'):
            defaults = dict(s.get('defaults', {}))
            defaults.update(s.get(direction.lower() + '_defaults', {}))
            for option, value in defaults.items():
                if option not in policy['options']:
                    fail(f"SerDe {s['id']}: unknown option {option}")
                if value.startswith('@'):
                    lines.append(
                        f"    {{HiveSerDe::{s['id']}, SerDeDirection::{direction}, {option_enum(option)}, nullptr, "
                        f"{option_enum(value[1:])}}},"
                    )
                else:
                    lines.append(
                        f"    {{HiveSerDe::{s['id']}, SerDeDirection::{direction}, {option_enum(option)}, "
                        f"{c_string(value)}, SerDeOption::NONE}},"
                    )
    lines += ['};', '', '//! in priority order: of two rules for one option the first one set wins (combine FIRST)',
              'static const SerDePropertyRule SERDE_PROPERTY_RULES[] = {']
    for prop in policy['properties']:
        for serde in prop['serdes']:
            for direction in ('read', 'write'):
                spec = prop[direction]
                transform = spec.get('transform', 'text')
                lines.append(
                    f"    {{HiveSerDe::{serde}, SerDeDirection::{direction.upper()}, {c_string(prop['key'])}, "
                    f"{str(prop.get('prefix', False)).lower()}, SerDeAction::{ACTIONS[spec['action']]}, "
                    f"{option_enum(spec.get('option'))}, SerDeTransform::{TRANSFORMS[transform]}, "
                    f"SerDeCondition::{CONDITIONS[spec.get('refuse_when')]}, "
                    f"SerDeCombine::{'ANY' if spec.get('combine') == 'any' else 'FIRST'}, "
                    f"{c_string(spec.get('message'))}}},"
                )
    lines += ['};', '', 'static const SerDeCreateParameter SERDE_CREATE_PARAMETERS[] = {']
    for s in policy['serdes']:
        for key, value in s.get('create_parameters', {}).items():
            lines.append(f"    {{HiveSerDe::{s['id']}, {c_string(key)}, nullptr, {c_string(value)}}},")
    for prop in policy['properties']:
        if 'create_option' in prop:
            for serde in prop['serdes']:
                lines.append(
                    f"    {{HiveSerDe::{serde}, {c_string(prop['key'])}, {c_string(prop['create_option'])}, nullptr}},"
                )
    lines += ['};', '', '} // namespace duckdb', '// clang-format on', '']
    return '\n'.join(lines)


