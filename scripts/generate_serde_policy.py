def md(value):
    return value.replace('|', '\\|')


def show_value(value):
    if value is None:
        return ''
    if value == '':
        return "`''`"
    shown = ''.join('\\%03o' % ord(c) if ord(c) < 32 else c for c in value)
    return '`' + md(shown) + '`'


def describe(spec, policy):
    action = spec['action']
    when = CONDITION_TEXT[spec.get('refuse_when')]
    if action == 'apply':
        option = policy['options'][spec['option']]
        text = f"{spec['option']} ({spec.get('transform', 'text')})"
        if when:
            text += f'; refused {when}'
        return text
    if action == 'ignore':
        return 'ignored'
    if action == 'warn':
        return f'not applied, logged {when}'
    return f'refused {when}'


def generate_docs(policy):
    serdes = {s['id']: s for s in policy['serdes']}
    out = [
        '<!-- This file is generated by scripts/generate_serde_policy.py from src/core/serde_policy.json, do not edit -->',
        '# SerDes and SerDe properties',
        '',
        "The SerDe (SerializationLibrary) of a Hive table decides how its files are read and written. A table property "
        "overrides the SerDe property of the same name and keys are case-sensitive, as in Hive. Properties not listed "
        "here are ignored. Partitions are read with the table's SerDe properties.",
        '',
        '| SerDe | Matched by | Files | Read with | Written | Notes |',
        '|---|---|---|---|---|---|',
    ]
    for s in policy['serdes']:
        written = 'yes' if s['writable'] else 'no: ' + s.get('write_refusal', '')
        notes = s.get('notes', '')
        checks = [CHECK_TEXT[c] for c in s.get('checks', [])] + [CHECK_TEXT[c] for c in s.get('write_checks', [])]
        if checks:
            notes = (notes + ' ' if notes else '') + '; '.join(checks).capitalize() + '.'
        out.append(
            f"| {s['name']} (`{s['library']}`) | `{s['match']}` | {s['format'].lower()} | {md(s['reader'])} | "
            f"{md(written)} | {md(notes)} |"
        )
    for u in policy['unsupported_serdes']:
        out.append(f"| {u['name']} | `{u['match']}` | - | not supported: {md(u['reason'])} | no | |")
    out += ['', 'Any other SerDe is not supported. A table of an unsupported SerDe can be inspected with '
            '`glue_get_table_response()`.', '']
    out += ['## Properties', '',
            'Read and Write say what the property does: the reader / writer option it sets (with the conversion of '
            'its value), `ignored` (harmless), `not applied, logged` (the read succeeds and a warning is logged, '
            "`CALL enable_logging(level := 'warning')`) or `refused` (the query fails).", '',
            '| SerDe | Property | Default | Read | Write | CREATE TABLE option | Notes |',
            '|---|---|---|---|---|---|---|']
    for prop in policy['properties']:
        for serde in prop['serdes']:
            s = serdes[serde]
            key = prop['key'] + ('*' if prop.get('prefix') else '')
            write = describe(prop['write'], policy) if s['writable'] else 'table not written'
            out.append(
                f"| {s['name']} | `{key}` | {show_value(prop.get('default'))} | {md(describe(prop['read'], policy))} | "
                f"{md(write)} | {prop.get('create_option', '')} | {md(prop.get('notes', ''))} |"
            )
    out += ['', '## Options', '', '| Option | Reader | Writer |', '|---|---|---|']
    for name, option in policy['options'].items():
        out.append(f"| {name} | {md(option['reader'])} | {md(option['writer'])} |")
    out += ['', '## Conversions', '', '| Conversion | Meaning |', '|---|---|']
    for name, text in policy['transforms'].items():
        out.append(f'| {name} | {md(text)} |')
    out.append('')
    return '\n'.join(out)


